    def rd(key:str)->pd.DataFrame: return pd.read_json(StringIO(str(z[key][0])),orient="records")
    data=SpatiotemporalTissueData(rd("nodes_json"),rd("edges_json"),rd("regulatory_json"),rd("organelle_json"),rd("tissue_json"))
    required_nodes={"row_id","donor_id","section_id","cell_id","cell_type","time","x","y","stress","damage","reserve","inflammation","next_stress","next_damage","next_reserve","next_inflammation","delta_t"}
    required_edges={"source","target","section_id","time","relation","distance","ligand_signal","receptor_signal","source_stress","source_damage","source_inflammation","edge_active"}
    miss=sorted(required_nodes-set(data.nodes.columns)); miss_e=sorted(required_edges-set(data.edges.columns))
    if miss or miss_e: raise ValueError(f"external spatiotemporal dataset missing nodes={miss}, edges={miss_e}")
    return data


